function buildToc(container, headings, articleId) {
  if (!container) return;
  if (!headings.length) {
    container.innerHTML = `<p class="empty-state">No headings found in the markdown yet.</p>`;
    return;
  }

  container.innerHTML = headings.map((heading) => `
    <a href="#${heading.id}" data-toc-link>${escapeHtml(heading.text)}</a>
  `).join("");

  const links = Array.from(container.querySelectorAll("[data-toc-link]"));
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      links.forEach((link) => {
        const active = link.getAttribute("href") === `#${entry.target.id}`;
        link.classList.toggle("is-active", active);
      });
    });
  }, {
    rootMargin: "-30% 0px -55% 0px",
    threshold: 0.1,
  });

  headings.forEach((heading) => {
    const element = document.getElementById(heading.id);
    if (element) observer.observe(element);
  });
}

function updateSeo(post, meta) {
  const title = meta.seoTitle || post.seoTitle || post.title;
  const description = meta.description || post.description || "";
  document.title = `${title} | Frost & Fashion`;
  updateMeta("description", description);
  updateMeta("og:title", title, "property");
  updateMeta("og:description", description, "property");
  updateMeta("og:image", post.coverImage, "property");
  updateMeta("twitter:card", "summary_large_image", "name");
}

function updateMeta(name, content, attribute = "name") {
  let meta = document.head.querySelector(`meta[${attribute}="${name}"]`);
  if (!meta) {
    meta = document.createElement("meta");
    meta.setAttribute(attribute, name);
    document.head.appendChild(meta);
  }
  meta.setAttribute("content", content);
}

