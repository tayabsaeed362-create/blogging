async function loadPosts() {
  if (cachedPosts) return cachedPosts;

  const fromNetwork = await Promise.allSettled(BLOGS.map(async (post) => {
    if (window.location.protocol === "file:") {
      throw new Error("Local file protocol fallback");
    }
    const response = await fetch(post.source, { cache: "no-store" });
    if (!response.ok) {
      throw new Error(`Unable to load ${post.source}`);
    }
    const markdown = await response.text();
    return normalizePost(markdown, post);
  }));

  const networkPosts = fromNetwork
    .filter((result) => result.status === "fulfilled")
    .map((result) => result.value);

  if (networkPosts.length) {
    cachedPosts = networkPosts;
    return networkPosts;
  }

  const fallbackPosts = BLOGS.map((post) => normalizePost(post.markdown, post));
  cachedPosts = fallbackPosts;
  return fallbackPosts;
}

function normalizePost(markdown, fallback) {
  const parsed = parseMarkdown(markdown);
  const meta = parsed.meta;
  return {
    ...fallback,
    title: meta.title || fallback.title,
    seoTitle: meta.seoTitle || fallback.seoTitle,
    description: meta.description || fallback.description,
    category: meta.category || fallback.category,
    slug: meta.slug || fallback.slug,
    coverImage: normalizeImagePath(meta.cover || fallback.coverImage),
    tags: meta.tags ? meta.tags.split(",").map((tag) => tag.trim()).filter(Boolean) : fallback.tags,
    markdown,
    parsed,
  };
}

function normalizeImagePath(path) {
  if (!path) return "images/image1.jpg";
  return path.replace(/^\.\.\//, "").replace(/^\.\//, "");
}

function parseMarkdown(markdown) {
  const { meta, body } = splitFrontMatter(markdown);
  const lines = body.replace(/\r\n/g, "\n").split("\n");
  const html = [];
  const headings = [];
  const paragraph = [];
  const listItems = [];
  let mode = null;
  let excerpt = "";

  const flushParagraph = () => {
    if (!paragraph.length) return;
    const text = paragraph.join(" ").trim();
    if (text) {
      if (!excerpt) excerpt = stripMarkdown(text);
      html.push(`<p>${formatInline(text)}</p>`);
    }
    paragraph.length = 0;
  };

  const flushList = () => {
    if (!listItems.length) return;
    html.push(`<ul>${listItems.map((item) => `<li>${formatInline(item)}</li>`).join("")}</ul>`);
    listItems.length = 0;
  };

  for (const rawLine of lines) {
    const line = rawLine.trimEnd();
    const trimmed = line.trim();

    if (!trimmed) {
      flushParagraph();
      flushList();
      mode = null;
      continue;
    }

    const imageMatch = trimmed.match(/^!\[(.*?)\]\((.*?)\)$/);
    if (imageMatch) {
      flushParagraph();
      flushList();
      html.push(`
        <figure class="article-figure">
          <img src="${escapeHtml(normalizeImagePath(imageMatch[2]))}" alt="${escapeHtml(imageMatch[1])}" loading="lazy" data-fallback>
          <figcaption>${escapeHtml(imageMatch[1])}</figcaption>
        </figure>
      `);
      continue;
    }

    const headingMatch = trimmed.match(/^(#{1,3})\s+(.*)$/);
    if (headingMatch) {
      flushParagraph();
      flushList();
      const level = headingMatch[1].length;
      const text = headingMatch[2].trim();
      const id = slugify(text);
      headings.push({ level, text, id });
      html.push(`<h${level} id="${id}">${formatInline(text)}</h${level}>`);
      continue;
    }

    if (/^[-*]\s+/.test(trimmed)) {
      flushParagraph();
      mode = "list";
      listItems.push(trimmed.replace(/^[-*]\s+/, ""));
      continue;
    }

    if (mode === "list" && /^(\d+)\.\s+/.test(trimmed)) {
      flushParagraph();
      flushList();
      html.push(`<ol><li>${formatInline(trimmed.replace(/^\d+\.\s+/, ""))}</li></ol>`);
      continue;
    }

    paragraph.push(trimmed);
    mode = "paragraph";
  }

  flushParagraph();
  flushList();

  return {
    meta: {
      title: meta.title || "",
      seoTitle: meta.seo_title || meta.seoTitle || "",
      slug: meta.slug || "",
      description: meta.description || "",
      cover: meta.cover || "",
      category: meta.category || "",
      tags: meta.tags || "",
    },
    html: html.join("\n"),
    headings,
    excerpt,
  };
}

function splitFrontMatter(markdown) {
  const normalized = markdown.replace(/\r\n/g, "\n");
  if (!normalized.startsWith("---\n")) {
    return { meta: {}, body: normalized };
  }

  const endIndex = normalized.indexOf("\n---\n", 4);
  if (endIndex === -1) {
    return { meta: {}, body: normalized };
  }

  const metaBlock = normalized.slice(4, endIndex);
  const body = normalized.slice(endIndex + 5);
  const meta = {};

  metaBlock.split("\n").forEach((line) => {
    const index = line.indexOf(":");
    if (index === -1) return;
    const key = line.slice(0, index).trim();
    const value = line.slice(index + 1).trim();
    meta[key] = value;
  });

  return { meta, body };
}

function formatInline(text) {
  let output = escapeHtml(text);
  output = output.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
  output = output.replace(/`([^`]+)`/g, "<code>$1</code>");
  output = output.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');
  return output;
}

function stripMarkdown(text) {
  return text
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1")
    .replace(/[#*_>-]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function attachImageFallbacks(scope) {
  scope.querySelectorAll("img[data-fallback]").forEach((image) => {
    if (image.dataset.bound === "true") return;
    image.dataset.bound = "true";
    image.addEventListener("error", () => {
      image.src = PLACEHOLDER_IMAGE;
      image.classList.add("is-fallback");
    }, { once: true });
  });
}

function showHomeError() {
  const grid = document.querySelector("[data-post-grid]");
  if (grid) {
    grid.innerHTML = `<div class="empty-state">The blog list could not be loaded.</div>`;
  }
}

function showPostError() {
  const article = document.querySelector("[data-post-article]");
  if (article) {
    article.innerHTML = `<div class="empty-state">The blog post could not be loaded.</div>`;
  }
}
